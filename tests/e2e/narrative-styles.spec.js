import { test, expect } from './support/fixtures.js';

const profile = { fullName: 'Test Applicant', email: 'test@example.com', resumeContext: 'Built a form-filling tool that handles custom dropdowns reliably.', savedAnswers: { 'Saved answer': 'Keep my exact wording.' } };
const badgeSelector = '#kareer-inline-rewrite';

test('options style persists, reaches autofill, and supports a one-off textarea rewrite', async ({ kr }) => {
  await kr.seed({ profile, settings: { autoContinue: false, narrativeStyle: 'unknown', futureSetting: 'preserve' } });
  const options = await kr.context.newPage();
  await options.goto(`${kr.optionsUrl()}#models`);
  await expect(options.locator('#narrative-style')).toHaveValue('natural');
  await options.locator('#narrative-style').selectOption('warm-personal');
  await expect(options.locator('#style-description')).toContainText('personal connection');
  await expect(options.locator('#style-example')).toContainText('less like a chore');
  expect((await kr.readStorage('kr:settings')).narrativeStyle).toBe('unknown');
  await options.locator('#save-model').click();
  await expect.poll(async () => (await kr.readStorage('kr:settings')).narrativeStyle).toBe('warm-personal');
  await options.reload();
  await expect(options.locator('#narrative-style')).toHaveValue('warm-personal');
  expect((await kr.readStorage('kr:settings')).futureSetting).toBe('preserve');

  const page = await kr.context.newPage();
  await page.goto(kr.fixtureUrl('narrative-styles.html'));
  await kr.openPanel(page);
  await page.locator('#kr-autofill-btn').click();
  await expect(page.locator('#why')).not.toHaveValue('');
  await expect(page.locator('#kr-autofill-btn')).toBeEnabled();
  expect(kr.openrouter.requests).toHaveLength(1);
  expect(kr.openrouter.requests[0].body.messages[0].content).toContain('SELECTED WRITING STYLE: Warm & personal');
  await expect(page.locator('#saved')).toHaveValue('Keep my exact wording.');
  await expect(page.locator('#email')).toHaveValue('test@example.com');
  await page.locator('#kr-close-panel-btn').click();
  await page.locator('#why').focus();
  const badge = page.locator(badgeSelector);
  const style = badge.getByLabel('Writing style');
  await expect(style).toHaveValue('warm-personal');
  await style.selectOption('light-wit');
  expect(kr.openrouter.requests).toHaveLength(1);
  kr.openrouter.handler = () => ({ choices: [{ message: { content: 'Custom dropdowns had other plans. I built a tool that handles them.' } }] });
  kr.openrouter.delayMs = 500;
  await badge.getByRole('button').evaluate(button => { button.click(); button.click(); });
  await expect(style).toBeDisabled();
  await expect(page.locator('#why')).toHaveValue('Custom dropdowns had other plans. I built a tool that handles them.');
  expect(kr.openrouter.requests).toHaveLength(2);
  const rewrite = kr.openrouter.requests[1].body;
  expect(rewrite.messages[0].content).toContain('SELECTED WRITING STYLE: Light wit');
  expect(rewrite.messages[1].content).toContain('600 characters');
  expect((await kr.readStorage('kr:settings')).narrativeStyle).toBe('warm-personal');
  await page.locator('#saved').focus();
  await expect(style).toHaveValue('warm-personal');
});

test('panel style saves and a keyboard contenteditable rewrite fits a narrow viewport', async ({ kr }) => {
  await kr.seed({ profile, settings: { narrativeStyle: 'natural', autoContinue: false } });
  const page = await kr.context.newPage();
  await page.goto(kr.fixtureUrl('narrative-styles.html'));
  await kr.openPanel(page);
  await page.locator('[data-tab=settings]').click();
  await page.locator('#kr-narrative-style').selectOption('story-led');
  await expect(page.locator('#kr-style-example')).toContainText('same obstacle');
  await page.locator('#kr-settings-form button[type=submit]').click();
  await expect.poll(async () => (await kr.readStorage('kr:settings')).narrativeStyle).toBe('story-led');
  await page.locator('#kr-close-panel-btn').click();
  await page.setViewportSize({ width: 360, height: 740 });
  await page.locator('#editor').focus();
  const badge = page.locator(badgeSelector);
  const style = badge.getByLabel('Writing style');
  await expect(style).toHaveValue('story-led');
  await style.focus();
  await page.waitForTimeout(450);
  await expect(badge).toBeVisible();
  const bounds = await badge.boundingBox();
  expect(bounds.x).toBeGreaterThanOrEqual(0);
  expect(bounds.x + bounds.width).toBeLessThanOrEqual(360);
  await style.selectOption('quietly-confident');
  expect(kr.openrouter.requests).toHaveLength(0);
  kr.openrouter.handler = () => ({ choices: [{ message: { content: 'I built a tool that handles custom dropdowns reliably.' } }] });
  await style.press('Tab');
  await expect(badge.getByRole('button')).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(page.locator('#editor')).toHaveText('I built a tool that handles custom dropdowns reliably.');
  expect(kr.openrouter.requests).toHaveLength(1);
  expect(kr.openrouter.requests[0].body.messages[1].content).toContain('Current Answer:\nI built a form-filling tool.');
  expect(kr.openrouter.requests[0].body.messages[0].content).toContain('SELECTED WRITING STYLE: Quietly confident');
  expect((await kr.readStorage('kr:settings')).narrativeStyle).toBe('story-led');
  await page.screenshot({ path: 'sample-output/narrative-style-mobile.png' });
});

test('a failed rewrite restores controls and retries without changing the saved style', async ({ kr }) => {
  await kr.seed({ profile, settings: { narrativeStyle: 'natural' } });
  const page = await kr.context.newPage();
  await page.goto(kr.fixtureUrl('narrative-styles.html'));
  await kr.openPanel(page);
  await page.locator('#kr-close-panel-btn').click();
  await page.locator('#why').fill('Original answer.');
  const badge = page.locator(badgeSelector);
  await badge.getByLabel('Writing style').selectOption('light-wit');
  kr.openrouter.status = 402;
  kr.openrouter.handler = () => ({ error: { message: 'Test failure' } });
  await badge.getByRole('button').click();
  await expect(badge.getByRole('button')).toHaveText('Rewrite failed');
  await expect(badge.getByRole('button')).toBeEnabled();
  await expect(badge.getByLabel('Writing style')).toBeEnabled();
  await expect(page.locator('#why')).toHaveValue('Original answer.');
  kr.openrouter.status = 200;
  kr.openrouter.handler = () => ({ choices: [{ message: { content: 'Rewritten answer.' } }] });
  await badge.getByRole('button').click();
  await expect(page.locator('#why')).toHaveValue('Rewritten answer.');
  expect(kr.openrouter.requests).toHaveLength(2);
  expect((await kr.readStorage('kr:settings')).narrativeStyle).toBe('natural');
});
