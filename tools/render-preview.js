import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { chromium } from '@playwright/test';

const outDir = path.resolve('sample-output');
// These one-page samples show the exported PDF, not a separate HTML template.
for (const [pdf, image] of [['sample-resume', 'resume-styling'], ['sample-cover-letter', 'cover-letter-styling']]) {
  execFileSync('pdftoppm', ['-png', '-singlefile', '-scale-to', '1400', path.join(outDir, `${pdf}.pdf`), path.join(outDir, image)]);
}
fs.writeFileSync(path.join(outDir, 'preview.html'), `<!doctype html>
<html lang="en"><meta charset="utf-8"><title>Kareer exported documents</title>
<style>
body{margin:0;padding:32px;background:#0f172a;color:#f8fafc;font:16px system-ui}
h1{font-size:24px}p{color:#94a3b8}.grid{display:grid;grid-template-columns:repeat(2,minmax(0,1fr));gap:24px}
article{background:#1e293b;padding:20px;border:1px solid #334155;border-radius:12px}
h2{font-size:18px;margin-top:0}img{display:block;width:100%;height:auto;background:white}
a{color:#38bdf8}@media(max-width:800px){.grid{grid-template-columns:1fr}}
</style><h1>Kareer exported documents</h1><p>Actual PDF pages generated by the extension’s pdfmake exporter.</p>
<div class="grid"><article><h2>Resume</h2><img id="resume-sheet" src="resume-styling.png" alt="Exported resume PDF"><p><a href="sample-resume.pdf">PDF</a> · <a href="sample-resume.docx">Word</a></p></article>
<article><h2>Cover letter</h2><img id="letter-sheet" src="cover-letter-styling.png" alt="Exported cover letter PDF"><p><a href="sample-cover-letter.pdf">PDF</a> · <a href="sample-cover-letter.docx">Word</a></p></article></div></html>`);

const browser = await chromium.launch();
try {
  const page = await browser.newPage({ viewport: { width: 1400, height: 1100 } });
  await page.goto(new URL(`file:///${path.join(outDir, 'preview.html').replace(/\\/g, '/')}`).href);
  await page.locator('#letter-sheet').evaluate(img => img.decode());
  await page.screenshot({ path: path.join(outDir, 'overview-preview.png'), fullPage: true });
} finally { await browser.close(); }
console.log(`Actual PDF previews saved to ${outDir}`);
